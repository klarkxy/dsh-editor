import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { collectDswVars } from './dsw-artifacts.mjs'

/*
 * Scans the published artifacts of the official DSH web packages for the
 * --dsw-* / --ds-* custom properties they read, and writes the sorted unique
 * list to src/design-system/dsw-vars.ts. `--check` verifies the committed file
 * matches the current artifacts instead of writing.
 */
const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const outFile = resolve(root, 'packages/dsh-editor-shell/src/design-system/dsw-vars.ts')

const manifests = [join(root, 'package.json'), join(root, 'apps/desktop/package.json')]
for (const entry of readdirSync(join(root, 'packages'), { withFileTypes: true })) {
  const manifest = join(root, 'packages', entry.name, 'package.json')
  if (entry.isDirectory() && existsSync(manifest)) manifests.push(manifest)
}
const vars = collectDswVars(manifests)
const body = `/**
 * GENERATED by scripts/scan-dsw-vars.mjs — do not edit by hand.
 * Every --dsw-* / --ds-* custom property read by the published official
 * artifacts (@deepseek-ai/dsh-client-ui-*, @deepseek-ai/dsh-web-frontend,
 * @klarkxy/*) under node_modules, deduplicated and sorted.
 */
export const DSW_VARS = [
${vars.map(name => `  '${name}',`).join('\n')}
] as const
`

const check = process.argv.includes('--check')
if (check) {
  let committed = ''
  try { committed = readFileSync(outFile, 'utf8') } catch { /* missing */ }
  if (committed !== body) {
    const previous = new Set([...committed.matchAll(/'(--(?:dsw|ds)-[^']+)'/g)].map(match => match[1]))
    console.error(JSON.stringify({
      missing: vars.filter(name => !previous.has(name)),
      obsolete: [...previous].filter(name => !vars.includes(name)),
    }))
    console.error('dsw-vars.ts is stale; review the artifact changes before regenerating.')
    process.exit(1)
  }
  console.log(`dsw-vars.ts is current (${vars.length} variables).`)
} else {
  writeFileSync(outFile, body)
  console.log(`wrote ${vars.length} variables to ${outFile}`)
}
