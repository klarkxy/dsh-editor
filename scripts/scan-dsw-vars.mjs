import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/*
 * Scans the published artifacts of the official DSH web packages for the
 * --dsw-* / --ds-* custom properties they read, and writes the sorted unique
 * list to src/design-system/dsw-vars.ts. `--check` verifies the committed file
 * matches the current artifacts instead of writing.
 */
const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const outFile = resolve(root, 'packages/dsh-editor-shell/src/design-system/dsw-vars.ts')

const pnpmDir = resolve(root, 'node_modules/.pnpm')
const roots = [resolve(root, 'node_modules/@deepseek-ai'), resolve(root, 'node_modules/@klarkxy')]
const wanted = name =>
  /^@deepseek-ai\+dsh-client-ui-/.test(name)
  || /^@deepseek-ai\+dsh-web-frontend/.test(name)
  || /^@klarkxy\+/.test(name)

const targets = []
try {
  for (const entry of readdirSync(pnpmDir)) {
    if (!wanted(entry)) continue
    const dir = join(pnpmDir, entry, 'node_modules')
    try {
      for (const scope of readdirSync(dir)) {
        const scoped = join(dir, scope)
        if (scope.startsWith('@')) {
          for (const pkg of readdirSync(scoped)) targets.push(join(scoped, pkg))
        } else targets.push(scoped)
      }
    } catch { /* not a package dir */ }
  }
} catch { /* no pnpm store */ }
for (const scopeDir of roots) {
  try {
    for (const pkg of readdirSync(scopeDir)) targets.push(join(scopeDir, pkg))
  } catch { /* scope absent */ }
}

const TEXT = /\.(?:[cm]?js|ts|tsx|css)$/
const files = []
const walk = dir => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' && dir.split(/[\\/]/).includes('node_modules')) {
        // Nested vendor copies still contain artifact CSS; keep walking them.
        walk(path)
      } else walk(path)
    } else if (entry.isFile() && TEXT.test(entry.name)) files.push(path)
  }
}
for (const target of targets) {
  try { if (statSync(target).isDirectory()) walk(target) } catch { /* missing */ }
}

const found = new Set()
for (const file of files) {
  let text
  try { text = readFileSync(file, 'utf8') } catch { continue }
  for (const match of text.matchAll(/--d?s(?:w)?-[a-zA-Z0-9_-]*/g)) {
    const name = match[0]
    if (!/^--(?:dsw|ds)-/.test(name)) continue
    if (name.endsWith('-')) continue // template-literal fragment, not a real var
    found.add(name)
  }
}

const vars = [...found].sort()
const body = `/**
 * GENERATED by scripts/scan-dsw-vars.mjs — do not edit by hand.
 * Every --dsw-* / --ds-* custom property read by the published official
 * artifacts (@deepseek-ai/dsh-client-ui-*, @deepseek-ai/dsh-web-frontend,
 * @klarkxy/*) under node_modules, deduplicated and sorted.
 */
export const DSW_VARS = [
${vars.map(name => `  '${name}',`).join('\n')}
] as const
`

const check = process.argv.includes('--check')
if (check) {
  let committed = ''
  try { committed = readFileSync(outFile, 'utf8') } catch { /* missing */ }
  if (committed !== body) {
    console.error('dsw-vars.ts is stale; run node scripts/scan-dsw-vars.mjs to regenerate.')
    process.exit(1)
  }
  console.log(`dsw-vars.ts is current (${vars.length} variables).`)
} else {
  writeFileSync(outFile, body)
  console.log(`wrote ${vars.length} variables to ${outFile}`)
}
